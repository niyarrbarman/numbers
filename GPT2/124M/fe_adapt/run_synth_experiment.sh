#!/bin/bash
#
# Synthetic arithmetic A/B experiment.
# Submits SLURM jobs with dependency chain:
#   1. Generate synthetic data (CPU)
#   2a. Train base LoRA    }  parallel
#   2b. Train adapted LoRA }
#   3. Benchmark both (arithmetic eval)
#
# Usage:
#   bash run_synth_experiment.sh
#
set -euo pipefail
mkdir -p slurm

SCRIPT_DIR="/work/m24047/m24047brmn/numbers/GPT2/124M/fe_adapt"
IMAGE="/work/conteneurs/calmip/nemo_25.04.03_arm.sif"

# Data paths
DATA_DIR="/tmpdir/m24047brmn/numbers/data/synth_arith"
BASE_DATA="${DATA_DIR}/base"
ADAPTED_DATA="${DATA_DIR}/adapted"

# Model paths
PRETRAINED_CKPT="/tmpdir/m24047brmn/numbers/checkpoints/baby_luciole_converted.pt"
STAGE1_CKPT="/tmpdir/m24047brmn/numbers/model_checkpoints/luciole_fe_adapt/ckpt.pt"

# Output paths
BASE_OUT="/tmpdir/m24047brmn/numbers/model_checkpoints/synth_base_lora"
ADAPTED_OUT="/tmpdir/m24047brmn/numbers/model_checkpoints/synth_adapted_lora"

# Benchmark data (generated by generate_arithmetic_data.py)
ARITH_BENCH="/tmpdir/m24047brmn/numbers/data/arithmetic_bench.json"

APPTAINER="apptainer exec --nv \
  --env PYTHONUSERBASE=${MYENVS}/numbers \
  --env TIKTOKEN_CACHE_DIR=/tmpdir/m24047brmn/tiktoken_cache \
  --env PYTHONUNBUFFERED=1 \
  --bind /tmpdir,/work \
  ${IMAGE}"

echo "=========================================="
echo "Synthetic Arithmetic A/B Experiment"
echo "  Data:          ${DATA_DIR}"
echo "  Pretrained:    ${PRETRAINED_CKPT}"
echo "  Stage 1:       ${STAGE1_CKPT}"
echo "  Base output:   ${BASE_OUT}"
echo "  Adapted out:   ${ADAPTED_OUT}"
echo "=========================================="

# --- Step 1: Generate synthetic data (CPU, short) ---
JOB_GEN=$(sbatch --parsable <<EOF
#!/bin/bash
#SBATCH -J synth_gen
#SBATCH -N 1
#SBATCH -n 1
#SBATCH -p small
#SBATCH --time=01:00:00
#SBATCH --output=slurm/%x_%j.out

set -euo pipefail
module load gnu/11.2.0

# Generate synthetic arithmetic data (50k train, 3k val, 3k test)
${APPTAINER} python3 ${SCRIPT_DIR}/generate_synth_math.py \
  --out_dir ${DATA_DIR} \
  --n_train 50000 \
  --n_val 3000 \
  --n_test 3000

# Also generate arithmetic benchmark data if not already present
if [ ! -f ${ARITH_BENCH} ]; then
  ${APPTAINER} python3 ${SCRIPT_DIR}/generate_arithmetic_data.py \
    --out_path ${ARITH_BENCH} \
    --n_problems 1000 \
    --seed 42
fi

echo "Data generation complete."
EOF
)
echo "Submitted data gen job: ${JOB_GEN}"

# --- Step 2a: Train base LoRA (GPU, 6k steps) ---
JOB_BASE=$(sbatch --parsable --dependency=afterok:${JOB_GEN} <<EOF
#!/bin/bash
#SBATCH -J synth_base_lora
#SBATCH -N 1
#SBATCH -n 1
#SBATCH --gres=gpu:1
#SBATCH -p small
#SBATCH --time=12:00:00
#SBATCH --output=slurm/%x_%j.out

set -euo pipefail
module load gnu/11.2.0

${APPTAINER} python3 ${SCRIPT_DIR}/train_tulu_lora.py \
  use_adapter=False \
  pretrained_ckpt=${PRETRAINED_CKPT} \
  data_dir=${BASE_DATA} \
  out_dir=${BASE_OUT} \
  block_size=256 \
  batch_size=8 \
  gradient_accumulation_steps=20 \
  lora_rank=16 \
  lora_alpha=32 \
  lora_dropout=0.05 \
  lora_targets=q_proj,v_proj,k_proj,o_proj \
  max_iters=6000 \
  learning_rate=3e-4 \
  lora_lr_scale=1.0 \
  warmup_iters=300 \
  lr_decay_iters=6000 \
  min_lr=3e-5 \
  num_norm_match=True \
  eval_interval=1000 \
  diag_interval=100 \
  sample_interval=500 \
  log_interval=10

echo "Base LoRA training complete."
EOF
)
echo "Submitted base LoRA job: ${JOB_BASE} (depends on ${JOB_GEN})"

# --- Step 2b: Train adapted LoRA (GPU, 6k steps) ---
JOB_ADAPT=$(sbatch --parsable --dependency=afterok:${JOB_GEN} <<EOF
#!/bin/bash
#SBATCH -J synth_adapt_lora
#SBATCH -N 1
#SBATCH -n 1
#SBATCH --gres=gpu:1
#SBATCH -p small
#SBATCH --time=12:00:00
#SBATCH --output=slurm/%x_%j.out

set -euo pipefail
module load gnu/11.2.0

${APPTAINER} python3 ${SCRIPT_DIR}/train_tulu_lora.py \
  use_adapter=True \
  stage1_ckpt=${STAGE1_CKPT} \
  data_dir=${ADAPTED_DATA} \
  out_dir=${ADAPTED_OUT} \
  block_size=256 \
  batch_size=8 \
  gradient_accumulation_steps=20 \
  lora_rank=16 \
  lora_alpha=32 \
  lora_dropout=0.05 \
  lora_targets=q_proj,v_proj,k_proj,o_proj \
  max_iters=6000 \
  learning_rate=3e-4 \
  lora_lr_scale=1.0 \
  adapter_lr_scale=0.3 \
  warmup_iters=300 \
  lr_decay_iters=6000 \
  min_lr=3e-5 \
  num_norm_match=True \
  eval_interval=1000 \
  diag_interval=100 \
  sample_interval=500 \
  log_interval=10

echo "Adapted LoRA training complete."
EOF
)
echo "Submitted adapted LoRA job: ${JOB_ADAPT} (depends on ${JOB_GEN})"

# --- Step 3: Benchmark both with arithmetic eval ---
JOB_BENCH=$(sbatch --parsable --dependency=afterok:${JOB_BASE}:${JOB_ADAPT} <<EOF
#!/bin/bash
#SBATCH -J synth_bench
#SBATCH -N 1
#SBATCH -n 1
#SBATCH --gres=gpu:1
#SBATCH -p small
#SBATCH --time=04:00:00
#SBATCH --output=slurm/%x_%j.out

set -euo pipefail
module load gnu/11.2.0

echo "============================================================"
echo "BENCHMARK: Arithmetic eval (few-shot)"
echo "============================================================"

${APPTAINER} python3 ${SCRIPT_DIR}/benchmark_arithmetic.py \
  --base_ckpt ${BASE_OUT}/ckpt_merged.pt \
  --adapted_ckpt ${ADAPTED_OUT}/ckpt_merged.pt \
  --data_path ${ARITH_BENCH} \
  --max_samples 1000 \
  --max_new_tokens 128

echo ""
echo "============================================================"
echo "BENCHMARK: Forward-pass on synth test data"
echo "============================================================"

${APPTAINER} python3 ${SCRIPT_DIR}/benchmark_tulu.py \
  --base_ckpt ${BASE_OUT}/ckpt_merged.pt \
  --adapted_ckpt ${ADAPTED_OUT}/ckpt_merged.pt \
  --base_data_dir ${BASE_DATA} \
  --adapted_data_dir ${ADAPTED_DATA} \
  --n_forward_batches 200 \
  --n_gen_samples 100

echo "All benchmarks complete."
EOF
)
echo "Submitted benchmark job: ${JOB_BENCH} (depends on ${JOB_BASE}, ${JOB_ADAPT})"

echo ""
echo "=========================================="
echo "All jobs submitted:"
echo "  1. Data gen:      ${JOB_GEN}"
echo "  2a. Base LoRA:    ${JOB_BASE}"
echo "  2b. Adapted LoRA: ${JOB_ADAPT}"
echo "  3. Benchmark:     ${JOB_BENCH}"
echo ""
echo "Monitor: squeue -u \$USER"
echo "=========================================="
